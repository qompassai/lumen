//! Validation tests for the converter contract clauses (T-2/T-4):
//! solver naming + Manifold default, read-back verification of a
//! real export, and the edge-manifoldness census — including the
//! golden Blender fixture pair (D-730's proving test).

use lumen_factory::base::build_base_mesh;
use lumen_factory::convert::contract::{
    BooleanSolver, ConverterContract, ExportCensus, ExportFormat, ReadBackRequirement,
    TriangleMesh, UnionContract, census_read_back, edge_manifoldness, edge_manifoldness_glb,
    verify_read_back,
};
use lumen_factory::gltf::{parse_glb, write_glb};

fn watertight_contract() -> ConverterContract {
    ConverterContract {
        converter_id: "fixture-union/1".to_string(),
        export_format: ExportFormat::Glb,
        read_back: ReadBackRequirement::Required,
        union: Some(UnionContract::watertight()),
    }
}

#[test]
fn watertight_union_contract_names_manifold_and_validates() {
    let contract = watertight_contract();
    assert_eq!(
        contract.union.expect("union clause").solver,
        BooleanSolver::Manifold
    );
    contract.validate().expect("watertight contract validates");
}

#[test]
fn noncritical_union_may_name_the_exact_solver() {
    let contract = ConverterContract {
        union: Some(UnionContract::new(BooleanSolver::Exact, false)),
        ..watertight_contract()
    };
    contract
        .validate()
        .expect("named non-critical exact union validates");
}

#[test]
fn contract_serializes_with_its_clauses_named() {
    let json = serde_json::to_string(&watertight_contract()).expect("contract serializes");
    assert!(
        json.contains("\"converter_id\":\"fixture-union/1\""),
        "{json}"
    );
    assert!(json.contains("\"solver\":\"manifold\""), "{json}");
    assert!(json.contains("\"read_back\":\"required\""), "{json}");
}

/// A closed cube: 8 vertices, 12 triangles, every edge shared by
/// exactly two triangles.
fn cube_mesh() -> TriangleMesh {
    TriangleMesh {
        indices: vec![
            0, 2, 1, 0, 3, 2, // bottom
            4, 5, 6, 4, 6, 7, // top
            0, 1, 5, 0, 5, 4, // front
            3, 7, 6, 3, 6, 2, // back
            0, 4, 7, 0, 7, 3, // left
            1, 2, 6, 1, 6, 5, // right
        ],
        vertex_count: 8,
    }
}

#[test]
fn closed_cube_is_watertight() {
    let census = edge_manifoldness(&cube_mesh()).expect("cube censuses");
    assert!(census.watertight, "{census:?}");
    assert_eq!(census.boundary_edge_count, 0);
    assert_eq!(census.nonmanifold_edge_count, 0);
    assert_eq!(census.edge_count, 18);
    assert_eq!(census.triangle_count, 12);
}

#[test]
fn golden_fixture_manifold_union_is_watertight() {
    // D-730 proving fixture: generated by
    // blender/boolean_solver_fixture.py on Blender 5.2.3 — a slab
    // fused with a self-intersecting joined operand.
    let bytes = include_bytes!("fixtures/boolean-manifold.glb");
    let census = edge_manifoldness_glb(bytes).expect("manifold fixture censuses");
    assert!(census.watertight, "{census:?}");
    assert_eq!(census.boundary_edge_count, 0);
    assert_eq!(census.nonmanifold_edge_count, 0);
    // Pinned from the generator's own census of the same artifact
    // (boolean_solver_fixture.py, Blender 5.2.3): 26 vertices,
    // 48 triangles, 72 edges — a closed genus-0 census
    // (26 - 72 + 48 = 2).
    assert_eq!(census.vertex_count, 26);
    assert_eq!(census.triangle_count, 48);
    assert_eq!(census.edge_count, 72);
}

#[test]
fn read_back_of_a_real_export_passes() {
    let mesh = build_base_mesh().expect("base mesh builds");
    let bytes = write_glb(&mesh, &[]).expect("glb writes");
    let summary = parse_glb(&bytes).expect("export re-reads");
    let expected = ExportCensus::from(&summary);
    let report = verify_read_back(&bytes, &expected).expect("read-back verifies");
    assert!(report.pass);
    assert!(report.differences.is_empty());
    assert_eq!(report.actual, Some(expected));
}

#[test]
fn read_back_report_serializes_with_schema() {
    let mesh = build_base_mesh().expect("base mesh builds");
    let bytes = write_glb(&mesh, &[]).expect("glb writes");
    let summary = parse_glb(&bytes).expect("export re-reads");
    let report = census_read_back(&bytes, &ExportCensus::from(&summary));
    let json = serde_json::to_string(&report).expect("report serializes");
    assert!(
        json.contains("\"schema\":\"lumen.converter-read-back\""),
        "{json}"
    );
    assert!(json.contains("\"pass\":true"), "{json}");
}
