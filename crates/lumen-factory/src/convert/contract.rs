//! The named-converter contract clauses (four-video T-2 + T-4).
//!
//! Contract summary:
//! - Every converter that boolean-unions parts names its solver in
//!   its contract ([`UnionContract`]). A union step cannot be
//!   declared without a solver: the field is a [`BooleanSolver`],
//!   never an optional string, so "the default did it" is not a
//!   representable state. For watertightness-critical unions the
//!   solver must be [`BooleanSolver::Manifold`] (D-730): Blender's
//!   exact solver fails multi-part fusions of self-intersecting
//!   part stock outright (on Blender 5.2.3 the evaluated union is
//!   an empty mesh; on the source video's Blender it left holes),
//!   while Manifold returns the correct watertight union. The
//!   golden fixture pair proving this is generated by
//!   `blender/boolean_solver_fixture.py` and checked in under
//!   `tests/fixtures/boolean-{exact,manifold}.glb`.
//! - Every converter's success claim requires read-back
//!   verification (D-732): the exported bytes are re-read with the
//!   crate's independent GLB reader and censused; the census must
//!   match the expectation the converter declared, field by field.
//!   A mismatch — including an unreadable (e.g. truncated) export —
//!   is a typed failure carrying the census diff, never a success.
//! - [`edge_manifoldness`] is the census the solver clause is
//!   verified with: undirected edge incidence over a triangle mesh.
//!   A mesh is watertight iff it is non-empty and every edge is
//!   shared by exactly two non-degenerate triangles. An empty
//!   output is non-watertight by definition: a union of non-empty
//!   solids cannot legitimately produce one.
//! - Exports are glTF-first (D-586): the only export format this
//!   contract certifies is binary glTF (`.glb`).

#![forbid(unsafe_code)]

use std::collections::BTreeMap;

use serde::Serialize;
use serde_json::Value;

use crate::FactoryError;
