/// Schema identifier for the read-back report.
pub const READ_BACK_SCHEMA: &str = "lumen.converter-read-back";
/// Schema version for the read-back report.
pub const READ_BACK_VERSION: u32 = 1;
/// Maximum index count accepted by the edge-manifoldness census.
pub const INDEX_COUNT_MAX: usize = 3_000_000;

/// A named boolean solver. The contract names the solver with this
/// enum so an unnamed union is unrepresentable (D-730).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum BooleanSolver {
    /// Blender's exact solver (arbitrary-precision mesh boolean).
    Exact,
    /// The Manifold solver (manifold3d): the default — and the
    /// required choice — for watertightness-critical unions.
    Manifold,
}

impl BooleanSolver {
    /// The solver's name as written in contracts and reports.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Exact => "exact",
            Self::Manifold => "manifold",
        }
    }
}

/// One converter's boolean-union clause: the named solver plus
/// whether the union is watertightness-critical.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
pub struct UnionContract {
    /// The named solver every union step of the converter uses.
    pub solver: BooleanSolver,
    /// True when a non-watertight result would break the converter's
    /// downstream consumers (engine import, printing, shape keys).
    pub watertightness_critical: bool,
}

impl UnionContract {
    /// A union clause with an explicitly named solver.
    pub fn new(solver: BooleanSolver, watertightness_critical: bool) -> Self {
        Self {
            solver,
            watertightness_critical,
        }
    }

    /// The standard clause for a watertightness-critical union:
    /// Manifold, per D-730.
    pub fn watertight() -> Self {
        Self {
            solver: BooleanSolver::Manifold,
            watertightness_critical: true,
        }
    }

    /// Fail-closed validation: a watertightness-critical union must
    /// name the Manifold solver (D-730).
    pub fn validate(&self) -> Result<(), FactoryError> {
        if self.watertightness_critical && self.solver != BooleanSolver::Manifold {
            return Err(FactoryError::BadParam(format!(
                "watertightness-critical union names solver {}, D-730 requires manifold",
                self.solver.as_str()
            )));
        }
        Ok(())
    }
}

/// The export format a converter contract certifies. glTF-first
/// (D-586): binary glTF is the only certified export.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ExportFormat {
    /// Binary glTF 2.0 (`.glb`).
    Glb,
}

impl ExportFormat {
    /// The format's file-extension spelling.
    pub fn as_str(self) -> &'static str {
        match self {
            Self::Glb => "glb",
        }
    }
}

/// Whether a converter's success claim requires read-back
/// verification. Under D-732 it always does; the clause exists so
/// the requirement is named in every contract, not assumed.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum ReadBackRequirement {
    /// The export must be re-read and censused before success.
    Required,
}

/// One converter's contract: its id, its certified export format,
/// its read-back clause, and (when it unions parts) its union
/// clause.
#[derive(Clone, Debug, PartialEq, Eq, Serialize)]
pub struct ConverterContract {
    /// Converter id, e.g. `pmx-import/1` (name + `/` + version).
    pub converter_id: String,
    /// The certified export format.
    pub export_format: ExportFormat,
    /// The read-back clause (D-732).
    pub read_back: ReadBackRequirement,
    /// The union clause, present iff the converter boolean-unions
    /// parts (D-730).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub union: Option<UnionContract>,
}

impl ConverterContract {
    /// Fail-closed validation of the contract itself: the id must
    /// be a non-empty `name/version` token without whitespace, and
    /// the union clause (when present) must validate.
    pub fn validate(&self) -> Result<(), FactoryError> {
        if self.converter_id.is_empty()
            || !self.converter_id.contains('/')
            || self.converter_id.chars().any(char::is_whitespace)
        {
            return Err(FactoryError::BadParam(format!(
                "converter id {:?} is not a name/version token",
                self.converter_id
            )));
        }
        if let Some(union) = &self.union {
            union.validate()?;
        }
        Ok(())
    }
}

/// The census of one exported GLB, as compared by read-back
/// verification. Mirrors [`GlbSummary`] field for field.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct ExportCensus {
    /// Total triangle index count across primitives.
    pub index_count: usize,
    /// Number of joints in the first skin (0 when unskinned).
    pub joint_count: usize,
    /// Number of meshes.
    pub mesh_count: usize,
    /// Number of nodes.
    pub node_count: usize,
    /// Number of primitives across all meshes.
    pub primitive_count: usize,
    /// Morph target names, in document order.
    pub target_names: Vec<String>,
    /// Total vertex count across primitives.
    pub vertex_count: usize,
}

impl From<&GlbSummary> for ExportCensus {
    fn from(summary: &GlbSummary) -> Self {
        Self {
            index_count: summary.index_count,
            joint_count: summary.joint_count,
            mesh_count: summary.mesh_count,
            node_count: summary.node_count,
            primitive_count: summary.primitive_count,
            target_names: summary.target_names.clone(),
            vertex_count: summary.vertex_count,
        }
    }
}

/// One field-level difference between the expected and the actual
/// read-back census.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct CensusDifference {
    /// What the re-read export actually carried (`"<unreadable>"`
    /// when the export could not be parsed at all).
    pub actual: String,
    /// What the converter declared it would carry.
    pub expected: String,
    /// The census field that differs.
    pub field: String,
}

/// The read-back report: the expected census, the actual census
/// when the export could be re-read, and every difference found.
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct ReadBackReport {
    /// The census of the re-read export; `None` when the export
    /// could not be parsed (truncated, corrupt, wrong format).
    pub actual: Option<ExportCensus>,
    /// Every difference, in field order. Empty iff `pass`.
    pub differences: Vec<CensusDifference>,
    /// The census the converter declared.
    pub expected: ExportCensus,
    /// True iff the export re-read cleanly and matched exactly.
    pub pass: bool,
    /// Schema identifier, always [`READ_BACK_SCHEMA`].
    pub schema: String,
    /// Schema version, always [`READ_BACK_VERSION`].
    pub version: u32,
}

impl ReadBackReport {
    /// The differences as deterministic `field: expected X, actual
    /// Y` lines (the failure detail carried by the typed error).
    pub fn diff_lines(&self) -> String {
        self.differences
            .iter()
            .map(|d| format!("{}: expected {}, actual {}", d.field, d.expected, d.actual))
            .collect::<Vec<_>>()
            .join("; ")
    }
}

fn compare_field(
    differences: &mut Vec<CensusDifference>,
    field: &str,
    expected: &impl ToString,
    actual: &impl ToString,
) {
    let expected = expected.to_string();
    let actual = actual.to_string();
    if expected != actual {
        differences.push(CensusDifference {
            actual,
            expected,
            field: field.to_string(),
        });
    }
}

/// Census an exported GLB by re-reading it with the crate's
/// independent reader and compare it against `expected`, field by
/// field. Infallible by design: an unreadable export is a report
/// with `actual: None` and a `read_back` difference, not an error —
/// the caller decides whether the report gates a success claim
/// (see [`verify_read_back`]).
pub fn census_read_back(bytes: &[u8], expected: &ExportCensus) -> ReadBackReport {
    let mut differences: Vec<CensusDifference> = Vec::new();
    let actual = match parse_glb(bytes) {
        Ok(summary) => {
            let census = ExportCensus::from(&summary);
            compare_field(
                &mut differences,
                "index_count",
                &expected.index_count,
                &census.index_count,
            );
            compare_field(
                &mut differences,
                "joint_count",
                &expected.joint_count,
                &census.joint_count,
            );
            compare_field(
                &mut differences,
                "mesh_count",
                &expected.mesh_count,
                &census.mesh_count,
            );
            compare_field(
                &mut differences,
                "node_count",
                &expected.node_count,
                &census.node_count,
            );
            compare_field(
                &mut differences,
                "primitive_count",
                &expected.primitive_count,
                &census.primitive_count,
            );
            compare_field(
                &mut differences,
                "target_names",
                &expected.target_names.join(","),
                &census.target_names.join(","),
            );
            compare_field(
                &mut differences,
                "vertex_count",
                &expected.vertex_count,
                &census.vertex_count,
            );
            Some(census)
        }
        Err(error) => {
            differences.push(CensusDifference {
                actual: format!("<unreadable: {error}>"),
                expected: "a readable glb census".to_string(),
                field: "read_back".to_string(),
            });
            None
        }
    };
    ReadBackReport {
        pass: differences.is_empty(),
        actual,
        differences,
        expected: expected.clone(),
        schema: READ_BACK_SCHEMA.to_string(),
        version: READ_BACK_VERSION,
    }
}

/// The D-732 gate: a converter may claim success only when this
/// returns `Ok`. On any difference the error is
/// [`FactoryError::ReadBackMismatch`] carrying the census diff.
pub fn verify_read_back(
    bytes: &[u8],
    expected: &ExportCensus,
) -> Result<ReadBackReport, FactoryError> {
    let report = census_read_back(bytes, expected);
    if report.pass {
        Ok(report)
    } else {
        Err(FactoryError::ReadBackMismatch(report.diff_lines()))
    }
}

/// A triangle mesh as the edge census sees it: vertex count plus
/// triangle indices (three per triangle, in winding order).
#[derive(Clone, Debug, PartialEq)]
pub struct TriangleMesh {
    /// Triangle indices; length is a multiple of three.
    pub indices: Vec<u32>,
    /// Vertex count; every index is `< vertex_count`.
    pub vertex_count: usize,
}

/// The edge-manifoldness census of one triangle mesh (D-730's
/// verifying measurement).
#[derive(Clone, Debug, PartialEq, Serialize)]
pub struct EdgeManifoldness {
    /// Edges shared by exactly one triangle (holes / open seams).
    pub boundary_edge_count: usize,
    /// Triangles with a repeated index (zero area by construction).
    pub degenerate_triangle_count: usize,
    /// Distinct undirected edges.
    pub edge_count: usize,
    /// Edges shared by three or more triangles.
    pub nonmanifold_edge_count: usize,
    /// Triangle count (`indices.len() / 3`).
    pub triangle_count: usize,
    /// Vertex count of the censused mesh.
    pub vertex_count: usize,
    /// True iff the mesh is non-empty and every edge is shared by
    /// exactly two non-degenerate triangles.
    pub watertight: bool,
}

/// Census one triangle mesh by undirected edge incidence. Bounded:
/// at most [`MAX_PART_VERTICES`] vertices and [`INDEX_COUNT_MAX`]
/// indices; indices must be in range and the count a multiple of
/// three. Degenerate triangles are counted and their edges are not
/// admitted to the incidence table (a zero-area face shares no
/// boundary in any meaningful sense).
pub fn edge_manifoldness(mesh: &TriangleMesh) -> Result<EdgeManifoldness, FactoryError> {
    if mesh.vertex_count > MAX_PART_VERTICES {
        return Err(FactoryError::BadParam(format!(
            "vertex count {} exceeds bound {MAX_PART_VERTICES}",
            mesh.vertex_count
        )));
    }
    if mesh.indices.len() > INDEX_COUNT_MAX {
        return Err(FactoryError::BadParam(format!(
            "index count {} exceeds bound {INDEX_COUNT_MAX}",
            mesh.indices.len()
        )));
    }
    if !mesh.indices.len().is_multiple_of(3) {
        return Err(FactoryError::BadParam(format!(
            "index count {} is not a multiple of three",
            mesh.indices.len()
        )));
    }
    let vertex_bound = u32::try_from(mesh.vertex_count)
        .map_err(|_| FactoryError::BadParam("vertex count overflows u32".to_string()))?;
    if mesh.indices.iter().any(|&index| index >= vertex_bound) {
        return Err(FactoryError::BadParam(format!(
            "an index is out of range for {} vertices",
            mesh.vertex_count
        )));
    }
    let mut incidence: BTreeMap<(u32, u32), u32> = BTreeMap::new();
    let mut degenerate_triangle_count = 0usize;
    for triangle in mesh.indices.as_chunks::<3>().0 {
        let [a, b, c] = *triangle;
        if a == b || b == c || a == c {
            degenerate_triangle_count += 1;
            continue;
        }
        for (p, q) in [(a, b), (b, c), (c, a)] {
            let edge = if p < q { (p, q) } else { (q, p) };
            *incidence.entry(edge).or_default() += 1;
        }
    }
    let boundary_edge_count = incidence.values().filter(|&&count| count == 1).count();
    let nonmanifold_edge_count = incidence.values().filter(|&&count| count > 2).count();
    let triangle_count = mesh.indices.len() / 3;
    Ok(EdgeManifoldness {
        boundary_edge_count,
        degenerate_triangle_count,
        edge_count: incidence.len(),
        nonmanifold_edge_count,
        triangle_count,
        vertex_count: mesh.vertex_count,
        watertight: mesh.vertex_count > 0
            && triangle_count > 0
            && boundary_edge_count == 0
            && nonmanifold_edge_count == 0
            && degenerate_triangle_count == 0,
    })
}

fn accessor_u32_values(
    root: &Value,
    bin: &[u8],
    accessor_index: usize,
) -> Result<Vec<u32>, FactoryError> {
    let accessors = root
        .get("accessors")
        .and_then(Value::as_array)
        .ok_or_else(|| FactoryError::InvalidGlb("glb has no accessors".to_string()))?;
    let accessor = accessors.get(accessor_index).ok_or_else(|| {
        FactoryError::InvalidGlb(format!("accessor {accessor_index} out of range"))
    })?;
    let component_type = accessor
        .get("componentType")
        .and_then(Value::as_u64)
        .ok_or_else(|| FactoryError::InvalidGlb("accessor missing componentType".to_string()))?;
    let element_bytes: usize = match component_type {
        5123 => 2,
        5125 => 4,
        _ => {
            return Err(FactoryError::InvalidGlb(format!(
                "accessor {accessor_index} componentType {component_type} is not an index type"
            )));
        }
    };
    let count = accessor
        .get("count")
        .and_then(Value::as_u64)
        .ok_or_else(|| FactoryError::InvalidGlb("accessor missing count".to_string()))?;
    let count = usize::try_from(count)
        .map_err(|_| FactoryError::InvalidGlb("accessor count overflows usize".to_string()))?;
    if count > INDEX_COUNT_MAX {
        return Err(FactoryError::BadParam(format!(
            "accessor count {count} exceeds bound {INDEX_COUNT_MAX}"
        )));
    }
    let view_index = accessor
        .get("bufferView")
        .and_then(Value::as_u64)
        .ok_or_else(|| FactoryError::InvalidGlb("accessor missing bufferView".to_string()))?;
    let views = root
        .get("bufferViews")
        .and_then(Value::as_array)
        .ok_or_else(|| FactoryError::InvalidGlb("glb has no bufferViews".to_string()))?;
    let view = views
        .get(usize::try_from(view_index).unwrap_or(usize::MAX))
        .ok_or_else(|| FactoryError::InvalidGlb("bufferView out of range".to_string()))?;
    if let Some(stride) = view.get("byteStride").and_then(Value::as_u64)
        && stride != element_bytes as u64
    {
        return Err(FactoryError::InvalidGlb(
            "strided index accessors are not censused".to_string(),
        ));
    }
    let view_offset = view.get("byteOffset").and_then(Value::as_u64).unwrap_or(0);
    let accessor_offset = accessor
        .get("byteOffset")
        .and_then(Value::as_u64)
        .unwrap_or(0);
    let start = usize::try_from(view_offset + accessor_offset)
        .map_err(|_| FactoryError::InvalidGlb("accessor offset overflows usize".to_string()))?;
    let mut values = Vec::with_capacity(count);
    for i in 0..count {
        let at = start + i * element_bytes;
        let slice = bin
            .get(at..at + element_bytes)
            .ok_or_else(|| FactoryError::InvalidGlb("index accessor overruns BIN".to_string()))?;
        values.push(match element_bytes {
            2 => u32::from(u16::from_le_bytes([slice[0], slice[1]])),
            _ => u32::from_le_bytes([slice[0], slice[1], slice[2], slice[3]]),
        });
    }
    Ok(values)
}

fn canonical_position_key(position: [f32; 3]) -> [u32; 3] {
    position.map(|component| {
        // -0.0 and 0.0 are the same coordinate; canonicalize so
        // welding compares positions, not sign bits.
        if component == 0.0 {
            0.0f32.to_bits()
        } else {
            component.to_bits()
        }
    })
}

fn accessor_vec3_values(
    root: &Value,
    bin: &[u8],
    accessor_index: usize,
) -> Result<Vec<[f32; 3]>, FactoryError> {
    let accessors = root
        .get("accessors")
        .and_then(Value::as_array)
        .ok_or_else(|| FactoryError::InvalidGlb("glb has no accessors".to_string()))?;
    let accessor = accessors.get(accessor_index).ok_or_else(|| {
        FactoryError::InvalidGlb(format!("accessor {accessor_index} out of range"))
    })?;
    let component_type = accessor
        .get("componentType")
        .and_then(Value::as_u64)
        .ok_or_else(|| FactoryError::InvalidGlb("accessor missing componentType".to_string()))?;
    if component_type != 5126 {
        return Err(FactoryError::InvalidGlb(format!(
            "accessor {accessor_index} componentType {component_type} is not float"
        )));
    }
    if accessor.get("type").and_then(Value::as_str) != Some("VEC3") {
        return Err(FactoryError::InvalidGlb(format!(
            "accessor {accessor_index} is not a VEC3 position accessor"
        )));
    }
    let count = accessor
        .get("count")
        .and_then(Value::as_u64)
        .ok_or_else(|| FactoryError::InvalidGlb("accessor missing count".to_string()))?;
    let count = usize::try_from(count)
        .map_err(|_| FactoryError::InvalidGlb("accessor count overflows usize".to_string()))?;
    if count > INDEX_COUNT_MAX {
        return Err(FactoryError::BadParam(format!(
            "accessor count {count} exceeds bound {INDEX_COUNT_MAX}"
        )));
    }
    let view_index = accessor
        .get("bufferView")
        .and_then(Value::as_u64)
        .ok_or_else(|| FactoryError::InvalidGlb("accessor missing bufferView".to_string()))?;
    let views = root
        .get("bufferViews")
        .and_then(Value::as_array)
        .ok_or_else(|| FactoryError::InvalidGlb("glb has no bufferViews".to_string()))?;
    let view = views
        .get(usize::try_from(view_index).unwrap_or(usize::MAX))
        .ok_or_else(|| FactoryError::InvalidGlb("bufferView out of range".to_string()))?;
    if let Some(stride) = view.get("byteStride").and_then(Value::as_u64)
        && stride != 12
    {
        return Err(FactoryError::InvalidGlb(
            "strided position accessors are not censused".to_string(),
        ));
    }
    let view_offset = view.get("byteOffset").and_then(Value::as_u64).unwrap_or(0);
    let accessor_offset = accessor
        .get("byteOffset")
        .and_then(Value::as_u64)
        .unwrap_or(0);
    let start = usize::try_from(view_offset + accessor_offset)
        .map_err(|_| FactoryError::InvalidGlb("accessor offset overflows usize".to_string()))?;
    let mut values = Vec::with_capacity(count);
    for i in 0..count {
        let at = start + i * 12;
        let slice = bin.get(at..at + 12).ok_or_else(|| {
            FactoryError::InvalidGlb("position accessor overruns BIN".to_string())
        })?;
        values.push([
            f32::from_le_bytes([slice[0], slice[1], slice[2], slice[3]]),
            f32::from_le_bytes([slice[4], slice[5], slice[6], slice[7]]),
            f32::from_le_bytes([slice[8], slice[9], slice[10], slice[11]]),
        ]);
    }
    Ok(values)
}

/// Census a whole GLB's triangle edges: every primitive of every
/// mesh is admitted into one combined mesh. An exported mesh
/// carries no vertex identity beyond position — exporters split
/// vertices at normal/UV seams — so the census **welds vertices
/// at exactly coincident positions** (bitwise, with −0.0
/// canonicalized) before counting edge incidence; the reported
/// vertex count is the welded count. The in-memory census
/// ([`edge_manifoldness`]) counts by index identity instead,
/// which is the exact relation inside a build. A GLB with no
/// primitives censuses as the empty mesh (non-watertight).
pub fn edge_manifoldness_glb(bytes: &[u8]) -> Result<EdgeManifoldness, FactoryError> {
    let parts = parse_glb_parts(bytes)?;
    let root = &parts.json;
    let meshes = root
        .get("meshes")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    let mut indices: Vec<u32> = Vec::new();
    let mut weld: BTreeMap<[u32; 3], u32> = BTreeMap::new();
    for mesh in &meshes {
        let primitives = mesh
            .get("primitives")
            .and_then(Value::as_array)
            .cloned()
            .unwrap_or_default();
        for primitive in &primitives {
            let position_accessor = primitive
                .get("attributes")
                .and_then(|attrs| attrs.get("POSITION"))
                .and_then(Value::as_u64)
                .ok_or_else(|| {
                    FactoryError::InvalidGlb("primitive missing POSITION".to_string())
                })?;
            let position_accessor = usize::try_from(position_accessor).map_err(|_| {
                FactoryError::InvalidGlb("position accessor overflows usize".to_string())
            })?;
            let positions = accessor_vec3_values(root, &parts.bin, position_accessor)?;
            let mut local_to_welded: Vec<u32> = Vec::with_capacity(positions.len());
            for position in &positions {
                if position.iter().any(|component| !component.is_finite()) {
                    return Err(FactoryError::InvalidGlb(
                        "position accessor carries a non-finite coordinate".to_string(),
                    ));
                }
                let key = canonical_position_key(*position);
                let next = u32::try_from(weld.len())
                    .map_err(|_| FactoryError::InvalidGlb("welded count overflows u32".into()))?;
                local_to_welded.push(*weld.entry(key).or_insert(next));
            }
            let vertex_count = u32::try_from(positions.len())
                .map_err(|_| FactoryError::InvalidGlb("vertex count overflows u32".to_string()))?;
            let remap = |local: u32| -> Result<u32, FactoryError> {
                local_to_welded
                    .get(usize::try_from(local).unwrap_or(usize::MAX))
                    .copied()
                    .ok_or_else(|| {
                        FactoryError::InvalidGlb("index out of range for positions".to_string())
                    })
            };
            if let Some(index_accessor) = primitive.get("indices").and_then(Value::as_u64) {
                let index_accessor = usize::try_from(index_accessor).map_err(|_| {
                    FactoryError::InvalidGlb("index accessor overflows usize".to_string())
                })?;
                for value in accessor_u32_values(root, &parts.bin, index_accessor)? {
                    indices.push(remap(value)?);
                }
            } else {
                // Non-indexed primitive: vertices are their own indices.
                for value in 0..vertex_count {
                    indices.push(remap(value)?);
                }
            }
        }
    }
    edge_manifoldness(&TriangleMesh {
        indices,
        vertex_count: weld.len(),
    })
}
